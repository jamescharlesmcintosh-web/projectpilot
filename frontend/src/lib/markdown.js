import { toast } from "sonner";

function slug(s) {
  return (s || "plan").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);
}

export function downloadMarkdown(filename, text) {
  const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  toast.success(`Exported ${filename}`);
}

export async function copyMarkdown(text, label = "Markdown") {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
    } else {
      const ta = document.createElement("textarea");
      ta.value = text;
      ta.style.position = "fixed";
      ta.style.opacity = "0";
      document.body.appendChild(ta);
      ta.focus();
      ta.select();
      document.execCommand("copy");
      document.body.removeChild(ta);
    }
    toast.success(`${label} copied to clipboard`);
  } catch {
    toast.error("Copy failed — clipboard blocked");
  }
}

const bullets = (items) => (items && items.length ? items.map((i) => `- ${i}`).join("\n") : "_none_");

export function masterPlanToMarkdown(project, p) {
  const roadmap = (p.roadmap || [])
    .map(
      (r) =>
        `### ${r.number}. ${r.title}\n\n` +
        `- **Objective:** ${r.objective}\n` +
        `- **Recommended tier:** \`${r.recommended_tier}\`\n` +
        `- **Files:** ${r.files.length ? r.files.map((f) => `\`${f}\``).join(", ") : "_none_"}\n` +
        `- **Dependencies:** ${r.dependencies.length ? r.dependencies.map((d) => `#${d}`).join(", ") : "_none_"}\n` +
        `- **Acceptance criteria:**\n${r.acceptance_criteria.map((a) => `  - ${a}`).join("\n")}`
    )
    .join("\n\n");

  return `# Master Plan — ${project.name}

> Generated by ProjectPilot · ${new Date(p.created_at).toLocaleString()}

${p.summary || ""}

**Recommended stack:** ${(p.recommended_stack || []).map((s) => `\`${s}\``).join(", ")}

## Folder Structure

\`\`\`
${p.folder_structure || ""}
\`\`\`

## Component Architecture
${bullets(p.component_architecture)}

## Page & Section Structure
${bullets(p.page_structure)}

## Data Model
${bullets(p.data_model)}

## Animation Architecture
${bullets(p.animation_architecture)}

## Reusable Scroll-Chapter Pattern
${p.scroll_chapter_pattern || "_n/a_"}

## Desktop & Mobile Strategy
${p.responsive_strategy || "_n/a_"}

## Image & Performance Strategy
${p.image_performance_strategy || "_n/a_"}

## Accessibility Requirements
${bullets(p.accessibility_requirements)}

## Form & Enquiry Strategy
${p.form_strategy || "_n/a_"}

## SEO Requirements
${bullets(p.seo_requirements)}

## Git Checkpoint Strategy
${p.git_checkpoint_strategy || "_n/a_"}

## Testing Strategy
${p.testing_strategy || "_n/a_"}

## Deployment Strategy
${p.deployment_strategy || "_n/a_"}

## Implementation Roadmap

${roadmap}
`;
}

export function delegationToMarkdown(project, p) {
  const tasks = (p.tasks || [])
    .map(
      (t) =>
        `### ${t.number}. ${t.name}\n\n` +
        `- **Tier:** \`${t.recommended_tier}\`\n` +
        `- **Human approval:** ${t.requires_human_approval ? "Required before merge" : "Not required"}\n` +
        `- **Description:** ${t.description}\n` +
        `- **Dependencies:** ${t.dependencies.length ? t.dependencies.map((d) => `#${d}`).join(", ") : "_none_"}\n\n` +
        `**Model prompt:**\n\n\`\`\`\n${t.model_prompt}\n\`\`\`\n\n` +
        `- **Allowed files:** ${t.allowed_files.length ? t.allowed_files.map((f) => `\`${f}\``).join(", ") : "any"}\n` +
        `- **Blocked files:** ${t.blocked_files.length ? t.blocked_files.map((f) => `\`${f}\``).join(", ") : "_none_"}\n` +
        `- **Expected output:** ${t.expected_output}\n` +
        `- **Verification commands:**\n${t.verification_commands.map((c) => `  - \`${c}\``).join("\n")}\n` +
        `- **Git commit message:** \`${t.git_commit_message}\``
    )
    .join("\n\n");

  return `# AI Delegation Plan — ${project.name}

> Generated by ProjectPilot · ${new Date(p.created_at).toLocaleString()}
> ${(p.tasks || []).length} delegated tasks. Plans are for review — never executed automatically.

${tasks}
`;
}

